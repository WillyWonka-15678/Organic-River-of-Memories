import { test, expect } from '@playwright/test';
test('艺术阶段 1：自然流场与时间演变', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto('/?stage=1&qa=1');
  await expect.poll(() => page.evaluate(() => (window as any).__river?.frames ?? 0), { timeout: 45000 }).toBeGreaterThan(100);
  await page.keyboard.press('h');
  const first = await page.screenshot({ path: 'test-results/art-stage-1-a.png' });
  const frames = await page.evaluate(() => (window as any).__river.frames);
  await expect.poll(() => page.evaluate(() => (window as any).__river.frames), { timeout: 30000 }).toBeGreaterThan(frames + 100);
  const second = await page.screenshot({ path: 'test-results/art-stage-1-b.png' });
  expect(first.equals(second)).toBe(false);
  expect(errors).toEqual([]);
});
