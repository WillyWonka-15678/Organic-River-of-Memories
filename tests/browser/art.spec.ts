test('艺术阶段 2：实际轮廓采样、移动与缓慢恢复', async ({ page }) => {
  test.skip(process.env.RIVER_TEST_PRODUCTION === '1', '合成轮廓注入仅在开发 QA 模式开放');
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto('/?stage=2&qa=1');
  await expect.poll(() => page.evaluate(() => (window as any).__river?.frames ?? 0)).toBeGreaterThan(10);
  await page.evaluate(() => (window as any).__riverQA.injectSilhouette(0));
  await expect.poll(() => page.evaluate(() => (window as any).__river.presence)).toBeGreaterThan(.8);
  expect(await page.evaluate(() => (window as any).__riverQA.sampleField(.50,.72))).toBeLessThan(0);
  expect(await page.evaluate(() => (window as any).__riverQA.sampleField(.72,.74))).toBeLessThan(0);
  expect(await page.evaluate(() => (window as any).__riverQA.sampleField(.32,.74))).toBeGreaterThan(0);
  await page.keyboard.press('h');
  await page.screenshot({ path: 'test-results/art-stage-2-contour.png' });
  await page.evaluate(() => (window as any).__riverQA.injectSilhouette(6.5));
  const f = await page.evaluate(() => (window as any).__river.frames);
  await expect.poll(() => page.evaluate(() => (window as any).__river.frames), { timeout: 20000 }).toBeGreaterThan(f+70);
  await page.screenshot({ path: 'test-results/art-stage-2-motion.png' });
  await page.evaluate(() => (window as any).__riverQA.clearMask());
  expect(await page.evaluate(() => (window as any).__river.presence)).toBeGreaterThan(.5);
  await expect.poll(() => page.evaluate(() => (window as any).__river.presence), { timeout: 15000 }).toBeLessThan(.15);
  expect(errors).toEqual([]);
});
